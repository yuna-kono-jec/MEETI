create table if not exists public.participants (
    id uuid primary key default gen_random_uuid(),
    number bigint generated by default as identity unique not null,
    owner_id uuid not null default auth.uid(),
    nickname text not null,
    mbti text not null,
    interests text[] not null default '{}',
    message text not null default '',
    gender text not null default '未回答',
    age_group text not null default '未回答',
    photo_path text,
    created_at timestamptz not null default now(),
    constraint participants_mbti_length check (char_length(mbti) = 4),
    constraint participants_interests_limit check (cardinality(interests) <= 3)
);

alter table public.participants enable row level security;

drop policy if exists "participants_select_authenticated" on public.participants;
create policy "participants_select_authenticated"
on public.participants
for select
to authenticated
using (true);

drop policy if exists "participants_insert_own" on public.participants;
create policy "participants_insert_own"
on public.participants
for insert
to authenticated
with check (owner_id = auth.uid());

drop policy if exists "participants_update_own" on public.participants;
create policy "participants_update_own"
on public.participants
for update
to authenticated
using (owner_id = auth.uid())
with check (owner_id = auth.uid());

grant select, insert, update on public.participants to authenticated;
grant usage, select on sequence public.participants_number_seq to authenticated;

